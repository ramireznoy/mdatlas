// Tabler icons used by the UI. Each becomes a `ti-<name>` class in
// tabler-icons/icons.css. Browse https://tabler.io/icons and add names here.
const TABLER_ICONS = {
  version: '3.0.0',
  names: [
    'alert-circle', 'chevron-right', 'circle-check', 'device-floppy', 'eye',
    'folder', 'folder-open', 'folder-root', 'layout-sidebar-left-collapse',
    'layout-sidebar-left-expand', 'markdown', 'mood-empty', 'moon', 'pencil',
    'plug-connected-x', 'refresh', 'sun',
  ],
};

// Each icon is a CSS mask filled with the text colour, so `<i class="ti ti-x">`
// sizes with font-size and colours with `color`, like an icon font.
const ICON_CSS_HEADER = `/* Generated by scripts/vendor.js from @tabler/icons@${TABLER_ICONS.version} (MIT). Do not edit. */
.ti {
  display: inline-block;
  width: 1em;
  height: 1em;
  vertical-align: -0.125em;
  background-color: currentColor;
  -webkit-mask: var(--ti) center / contain no-repeat;
          mask: var(--ti) center / contain no-repeat;
}
@keyframes ti-spin { to { transform: rotate(360deg); } }
.ti-spin { animation: ti-spin 1s linear infinite; }
`;

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
  return res.text();
}

function svgToDataUri(svg) {
  const compact = svg
    .replace(/\s+class="[^"]*"/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\/>/, '') // invisible bounding box
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
  return `url("data:image/svg+xml,${encodeURIComponent(compact)}")`;
}

async function buildIcons(dest) {
  const base  = `${NPM}/@tabler/icons@${TABLER_ICONS.version}`;
  const rules = await Promise.all(TABLER_ICONS.names.map(async name =>
    `.ti-${name} { --ti: ${svgToDataUri(await fetchText(`${base}/icons/outline/${name}.svg`))}; }`));
  await mkdir(dest, { recursive: true });
  await writeFile(join(dest, 'icons.css'), ICON_CSS_HEADER + rules.join('\n') + '\n');
  await writeFile(join(dest, 'LICENSE'), await fetchText(`${base}/LICENSE`));
}

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
  const data = Buffer.from(await res.arrayBuffer());
  await mkdir(dirname(dest), { recursive: true });
  await writeFile(dest, data);
  return data.length;
}

await rm(VENDOR_DIR, { recursive: true, force: true });

let total = 0;
for (const { dir, files } of LIBS) {
  for (const [name, url] of Object.entries(files)) {
    const size = await download(url, join(VENDOR_DIR, dir, name));
    total += size;
    console.log(`  ${(size / 1024).toFixed(0).padStart(6)} KB  ${dir}/${name}`);
  }
}
await buildIcons(join(VENDOR_DIR, 'tabler-icons'));
console.log(`  ${TABLER_ICONS.names.length.toString().padStart(9)}     tabler-icons/icons.css (icons)`);

console.log(`\n  ${(total / 1024 / 1024).toFixed(2)} MB written to public/vendor/`);
